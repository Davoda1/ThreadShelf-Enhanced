export function codeDownloadExtension(rawLanguage = '') {
  const fence = String(rawLanguage ?? '')
    .trim()
    .toLowerCase()
    .split(/\s+/, 1)[0]
    .replace(/^\{\.?/, '')
    .replace(/\}$/, '')
    .replace(/^\./, '')
    .replace(/^(?:language|lang)-/, '');
  if (Object.hasOwn(CODE_FENCE_EXTENSIONS, fence)) return CODE_FENCE_EXTENSIONS[fence];
  const language = normalizeCodeLanguage(fence);
  return Object.hasOwn(CODE_LANGUAGE_EXTENSIONS, language)
    ? CODE_LANGUAGE_EXTENSIONS[language]
    : 'txt';
}

export function codeDownloadFileName(rawLanguage = '', index = 1) {
  const number = Number.isSafeInteger(index) && index > 0 ? index : 1;
  return `code-block-${number}.${codeDownloadExtension(rawLanguage)}`;
}
